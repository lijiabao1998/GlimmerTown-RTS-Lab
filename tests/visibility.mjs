import assert from 'node:assert/strict';
import { createWorld, center, idx, UNIT_KINDS, SUB, ORD_ATTACK } from '../src/sim/world.ts';
import { spotted, step } from '../src/sim/step.ts';
const w = createWorld(1944);
w.blds = []; w.occ.fill(0); w.units = w.units.slice(0, 2);
const [a, b] = w.units;
a.x = center(3); a.z = center(3); b.x = center(7); b.z = center(3); b.side = 1;
assert.equal(spotted(w, 0, b.x, b.z), true, 'clear sight');
w.blds = [{id:1, kind:0, x:5,z:3,w:1,d:1,floors:1,hp:100,maxHp:100}]; w.occ[idx(5,3)] = 1;
assert.equal(spotted(w, 0, b.x, b.z), false, 'intact building blocks sight');
assert.equal(spotted(w, 1, a.x, a.z), false, 'both sides blocked');
assert.equal(spotted(w, 0, center(5), center(3)), true, 'blocking building visible');
w.blds[0].hp = 70;
assert.equal(spotted(w, 0, b.x, b.z), false, 'roofless building blocks sight');
step(w, []);
assert.equal(w.shells.length, 0, 'hidden enemies not auto targeted');
w.blds[0].hp = 0;
assert.equal(spotted(w, 0, b.x, b.z), true, 'rubble opens sight');
step(w, [{t:'attack', side:0, ids:[a.id], target:b.id}]);
assert.equal(a.order, ORD_ATTACK);
const lastX = a.tx, lastZ = a.tz;
w.blds[0].hp = 100; b.x += SUB;
step(w, []);
assert.equal(a.tx, lastX, 'lost target keeps last known x');
assert.equal(a.tz, lastZ, 'lost target keeps last known z');
w.blds[0].hp = 0;
assert.equal(spotted(w, 0, a.x + UNIT_KINDS[a.kind].sight, a.z), true, 'exact sight radius');
assert.equal(spotted(w, 0, a.x + UNIT_KINDS[a.kind].sight + SUB, a.z), false, 'beyond sight');
a.alive = false;
assert.equal(spotted(w, 0, b.x, b.z), false, 'dead observer gives no sight');
console.log('visibility: 12 assertions passed');
// Real renderer instance lists: hidden bodies/discs/wrecks are not submitted.
const { BattleView } = await import('../src/render/battle.ts');
const { hashWorld } = await import('../src/sim/world.ts');
a.alive = true; w.blds[0].hp = 100;
const before = hashWorld(w), fog = new BattleView(w, false), open = new BattleView(w, false, false);
fog.update(0, 0, new Set()); open.update(0, 0, new Set());
assert.equal(fog.hull.count, 1, 'hidden hull omitted');
assert.equal(fog.turret.count, 1, 'hidden turret omitted');
assert.equal(fog.discs.count, 1, 'hidden team disc omitted');
assert.equal(open.hull.count, 2, 'escape valve shows both units');
assert.equal(hashWorld(w), before, 'render valve never changes simulation');
b.alive = false; fog.update(0, 0, new Set());
assert.equal(fog.hull.count, 1, 'hidden wreck omitted');
fog.dispose(); open.dispose();
console.log('visibility renderer: 6 assertions passed');
