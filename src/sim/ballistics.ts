// kind 這種兵在 d（位置單位）外的穿深（公釐）；不在表裡回傳 -1
export function penetration(kind: number, d: number): number {
  const p = PEN_MM[kind];
  if (!p) return -1;
  const m = Math.max(100, Math.floor((d * METERS_PER_CELL) / SUB));
  return Math.max(0, Math.floor((p[0] * 900 - (p[0] - p[1]) * (m - 100)) / 900));
}

// shooterKind 從 (sx, sz) 打來的一發，打在有裝甲的 t 身上：
//   -1＝這一發不歸這條規則管（目標沒有裝甲或不在表裡、射手不在表裡、步兵打開頂車），照舊規則算；
//    0＝彈開；1＝穿透。
export function apHit(shooterKind: number, sx: number, sz: number, t: Unit): number {
  const plate = ARMOR_MM[t.kind], target = UNIT_KINDS[t.kind];
  if (!plate || !target.armored || (UNIT_KINDS[shooterKind].men > 0 && target.openTop)) return -1;   // 步兵打開頂車照舊（R044）
  const pen = penetration(shooterKind, dist(sx, sz, t.x, t.z));
  if (pen < 0) return -1;
  return pen >= plate[armorFace(t, sx, sz)] ? 1 : 0;
}
